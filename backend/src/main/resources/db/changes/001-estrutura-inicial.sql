-- ============================================================
-- EASY MANAGER - Estrutura inicial do banco de dados
-- PostgreSQL 18
-- Cria tabelas, chaves, relacionamentos, restricoes e indices.
-- Nao apaga tabelas nem insere dados ficticios.
-- ============================================================

-- 1. Estrutura multiempresa
CREATE TABLE IF NOT EXISTS empresa (
    id_empresa BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    cnpj VARCHAR(18) UNIQUE,
    segmento VARCHAR(80),
    descricao TEXT,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    data_criacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    telefone VARCHAR(20),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    data_criacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS unidade (
    id_unidade BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa BIGINT NOT NULL,
    nome VARCHAR(150) NOT NULL,
    endereco VARCHAR(255),
    telefone VARCHAR(20),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_unidade_empresa FOREIGN KEY (id_empresa)
        REFERENCES empresa (id_empresa) ON DELETE CASCADE,
    CONSTRAINT uq_unidade_empresa UNIQUE (id_unidade, id_empresa)
);

CREATE TABLE IF NOT EXISTS cargo (
    id_cargo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa BIGINT NOT NULL,
    nome VARCHAR(100) NOT NULL,
    descricao TEXT,
    CONSTRAINT fk_cargo_empresa FOREIGN KEY (id_empresa)
        REFERENCES empresa (id_empresa) ON DELETE CASCADE,
    CONSTRAINT uq_cargo_empresa_nome UNIQUE (id_empresa, nome),
    CONSTRAINT uq_cargo_id_empresa UNIQUE (id_cargo, id_empresa)
);

CREATE TABLE IF NOT EXISTS permissao (
    id_permissao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    descricao TEXT
);

CREATE TABLE IF NOT EXISTS cargo_permissao (
    id_cargo BIGINT NOT NULL,
    id_permissao BIGINT NOT NULL,
    PRIMARY KEY (id_cargo, id_permissao),
    CONSTRAINT fk_cargo_permissao_cargo FOREIGN KEY (id_cargo)
        REFERENCES cargo (id_cargo) ON DELETE CASCADE,
    CONSTRAINT fk_cargo_permissao_permissao FOREIGN KEY (id_permissao)
        REFERENCES permissao (id_permissao) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS usuario_empresa (
    id_usuario_empresa BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL,
    id_empresa BIGINT NOT NULL,
    id_cargo BIGINT NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    data_vinculo TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_usuario_empresa_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_usuario_empresa_empresa FOREIGN KEY (id_empresa)
        REFERENCES empresa (id_empresa) ON DELETE CASCADE,
    CONSTRAINT fk_usuario_empresa_cargo FOREIGN KEY (id_cargo, id_empresa)
        REFERENCES cargo (id_cargo, id_empresa),
    CONSTRAINT uq_usuario_empresa UNIQUE (id_usuario, id_empresa)
);

-- 2. Operacao do estacionamento
CREATE TABLE IF NOT EXISTS funcionario (
    id_funcionario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa BIGINT NOT NULL,
    id_unidade BIGINT,
    id_usuario BIGINT UNIQUE,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150),
    telefone VARCHAR(20),
    cargo_funcao VARCHAR(100),
    data_admissao DATE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_funcionario_empresa FOREIGN KEY (id_empresa)
        REFERENCES empresa (id_empresa) ON DELETE CASCADE,
    CONSTRAINT fk_funcionario_unidade_empresa FOREIGN KEY (id_unidade, id_empresa)
        REFERENCES unidade (id_unidade, id_empresa),
    CONSTRAINT fk_funcionario_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE SET NULL,
    CONSTRAINT uq_funcionario_id_empresa UNIQUE (id_funcionario, id_empresa)
);

CREATE TABLE IF NOT EXISTS cliente (
    id_cliente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa BIGINT NOT NULL,
    nome VARCHAR(150) NOT NULL,
    telefone VARCHAR(20),
    email VARCHAR(150),
    data_cadastro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_cliente_empresa FOREIGN KEY (id_empresa)
        REFERENCES empresa (id_empresa) ON DELETE CASCADE,
    CONSTRAINT uq_cliente_id_empresa UNIQUE (id_cliente, id_empresa)
);

CREATE TABLE IF NOT EXISTS veiculo (
    id_veiculo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa BIGINT NOT NULL,
    id_cliente BIGINT,
    placa VARCHAR(10) NOT NULL,
    modelo VARCHAR(100),
    cor VARCHAR(50),
    CONSTRAINT fk_veiculo_cliente_empresa FOREIGN KEY (id_cliente, id_empresa)
        REFERENCES cliente (id_cliente, id_empresa),
    CONSTRAINT fk_veiculo_empresa FOREIGN KEY (id_empresa)
        REFERENCES empresa (id_empresa) ON DELETE CASCADE,
    CONSTRAINT uq_veiculo_empresa_placa UNIQUE (id_empresa, placa),
    CONSTRAINT uq_veiculo_id_empresa UNIQUE (id_veiculo, id_empresa)
);

CREATE TABLE IF NOT EXISTS estadia (
    id_estadia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa BIGINT NOT NULL,
    id_unidade BIGINT NOT NULL,
    id_veiculo BIGINT NOT NULL,
    id_funcionario_entrada BIGINT,
    id_funcionario_saida BIGINT,
    data_entrada TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_saida TIMESTAMP,
    valor_total NUMERIC(10,2) NOT NULL DEFAULT 0,
    status VARCHAR(30) NOT NULL DEFAULT 'EM_ANDAMENTO',
    CONSTRAINT fk_estadia_unidade_empresa FOREIGN KEY (id_unidade, id_empresa)
        REFERENCES unidade (id_unidade, id_empresa),
    CONSTRAINT fk_estadia_veiculo_empresa FOREIGN KEY (id_veiculo, id_empresa)
        REFERENCES veiculo (id_veiculo, id_empresa),
    CONSTRAINT fk_estadia_func_entrada_empresa FOREIGN KEY (id_funcionario_entrada, id_empresa)
        REFERENCES funcionario (id_funcionario, id_empresa),
    CONSTRAINT fk_estadia_func_saida_empresa FOREIGN KEY (id_funcionario_saida, id_empresa)
        REFERENCES funcionario (id_funcionario, id_empresa),
    CONSTRAINT ck_estadia_valor CHECK (valor_total >= 0),
    CONSTRAINT ck_estadia_datas CHECK (data_saida IS NULL OR data_saida >= data_entrada),
    CONSTRAINT ck_estadia_status CHECK (status IN ('EM_ANDAMENTO', 'FINALIZADA', 'CANCELADA')),
    CONSTRAINT uq_estadia_id_empresa UNIQUE (id_estadia, id_empresa)
);

-- 3. Avaliacoes e satisfacao
CREATE TABLE IF NOT EXISTS avaliacao (
    id_avaliacao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa BIGINT NOT NULL,
    id_unidade BIGINT,
    id_cliente BIGINT,
    nota INTEGER NOT NULL,
    comentario TEXT,
    sentimento VARCHAR(30),
    data_avaliacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_avaliacao_empresa FOREIGN KEY (id_empresa)
        REFERENCES empresa (id_empresa) ON DELETE CASCADE,
    CONSTRAINT fk_avaliacao_unidade_empresa FOREIGN KEY (id_unidade, id_empresa)
        REFERENCES unidade (id_unidade, id_empresa),
    CONSTRAINT fk_avaliacao_cliente_empresa FOREIGN KEY (id_cliente, id_empresa)
        REFERENCES cliente (id_cliente, id_empresa),
    CONSTRAINT ck_avaliacao_nota CHECK (nota BETWEEN 1 AND 5),
    CONSTRAINT ck_avaliacao_sentimento CHECK (sentimento IS NULL OR sentimento IN ('POSITIVO', 'NEGATIVO', 'NEUTRO'))
);

-- 4. Financeiro
CREATE TABLE IF NOT EXISTS pagamento (
    id_pagamento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estadia BIGINT NOT NULL,
    valor NUMERIC(10,2) NOT NULL,
    forma_pagamento VARCHAR(40) NOT NULL,
    data_pagamento TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(30) NOT NULL DEFAULT 'PAGO',
    CONSTRAINT fk_pagamento_estadia FOREIGN KEY (id_estadia)
        REFERENCES estadia (id_estadia) ON DELETE RESTRICT,
    CONSTRAINT ck_pagamento_valor CHECK (valor > 0),
    CONSTRAINT ck_pagamento_status CHECK (status IN ('PENDENTE', 'PAGO', 'ESTORNADO'))
);

CREATE TABLE IF NOT EXISTS despesa (
    id_despesa BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa BIGINT NOT NULL,
    id_unidade BIGINT,
    descricao VARCHAR(200) NOT NULL,
    categoria VARCHAR(100),
    valor NUMERIC(10,2) NOT NULL,
    data_despesa DATE NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT fk_despesa_empresa FOREIGN KEY (id_empresa)
        REFERENCES empresa (id_empresa) ON DELETE CASCADE,
    CONSTRAINT fk_despesa_unidade_empresa FOREIGN KEY (id_unidade, id_empresa)
        REFERENCES unidade (id_unidade, id_empresa),
    CONSTRAINT ck_despesa_valor CHECK (valor > 0)
);

-- 5. Acompanhamento de atividades dos funcionarios
CREATE TABLE IF NOT EXISTS atividade_funcionario (
    id_atividade BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa BIGINT NOT NULL,
    id_unidade BIGINT,
    id_funcionario BIGINT NOT NULL,
    descricao VARCHAR(255) NOT NULL,
    data_atividade TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    observacao TEXT,
    CONSTRAINT fk_atividade_funcionario_empresa FOREIGN KEY (id_funcionario, id_empresa)
        REFERENCES funcionario (id_funcionario, id_empresa),
    CONSTRAINT fk_atividade_unidade_empresa FOREIGN KEY (id_unidade, id_empresa)
        REFERENCES unidade (id_unidade, id_empresa),
    CONSTRAINT fk_atividade_empresa FOREIGN KEY (id_empresa)
        REFERENCES empresa (id_empresa) ON DELETE CASCADE
);

-- Indices para consultas frequentes e filtros por empresa
CREATE INDEX IF NOT EXISTS idx_unidade_empresa ON unidade (id_empresa);
CREATE INDEX IF NOT EXISTS idx_cargo_empresa ON cargo (id_empresa);
CREATE INDEX IF NOT EXISTS idx_usuario_empresa_empresa ON usuario_empresa (id_empresa);
CREATE INDEX IF NOT EXISTS idx_funcionario_empresa ON funcionario (id_empresa);
CREATE INDEX IF NOT EXISTS idx_cliente_empresa ON cliente (id_empresa);
CREATE INDEX IF NOT EXISTS idx_veiculo_empresa ON veiculo (id_empresa);
CREATE INDEX IF NOT EXISTS idx_estadia_empresa_data ON estadia (id_empresa, data_entrada);
CREATE INDEX IF NOT EXISTS idx_avaliacao_empresa_data ON avaliacao (id_empresa, data_avaliacao);
CREATE INDEX IF NOT EXISTS idx_despesa_empresa_data ON despesa (id_empresa, data_despesa);
CREATE INDEX IF NOT EXISTS idx_atividade_empresa_data ON atividade_funcionario (id_empresa, data_atividade);

-- Fim do script. Para conferir as tabelas no pgAdmin:
-- Schemas > public > Tables > Refresh.
